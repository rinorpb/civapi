using Civapi;
using Microsoft.EntityFrameworkCore;
using Serilog;
using Serilog.Events;

Log.Logger = new LoggerConfiguration()
    .MinimumLevel.Override("Microsoft.AspNetCore.Hosting", LogEventLevel.Warning)
    .MinimumLevel.Override("Microsoft.AspNetCore.Mvc", LogEventLevel.Warning)
    .MinimumLevel.Override("Microsoft.AspNetCore.Routing", LogEventLevel.Warning)
    .WriteTo.Console()
    .CreateLogger();

try
{
    var builder = WebApplication.CreateBuilder(args);

    // Add services to the container.
    // Learn more about configuring OpenAPI at https://aka.ms/aspnet/openapi
    builder.Services.AddOpenApi();
    
    //database config
    string? connectionString = builder.Configuration.GetConnectionString("DocumentsDatabase") ?? "Data Source=Documents.db";
    builder.Services.AddSqlite<DocumentDb>(connectionString);
    
    builder.Services.AddSerilog();
    builder.Services.AddAuthentication().AddJwtBearer();
    builder.Services.AddAuthorization();

    builder.Services.AddAuthorizationBuilder()
        .AddPolicy("upload", policy =>
            policy
                .RequireRole("admin", "employee"))
        .AddPolicy(AccessLevels.Sensitive, policy =>
            policy
                .RequireRole("admin")
                .RequireClaim("scope", AccessLevels.Sensitive))
        .AddPolicy(AccessLevels.Personal, policy =>
            policy
                .RequireRole("admin", "employee")
                .RequireClaim("scope", AccessLevels.Personal))
        .AddPolicy(AccessLevels.Internal, policy =>
            policy
                .RequireRole("admin", "employee")
                .RequireClaim("scope", AccessLevels.Internal));

    var app = builder.Build();
    
    app.UseSerilogRequestLogging();
    app.UseAuthentication();
    app.UseAuthorization();

    // Configure the HTTP request pipeline.
    if (app.Environment.IsDevelopment())
    {
        app.MapOpenApi();
    }

    app.UseHttpsRedirection();

    app.ConfigureDocumentsApi();
    app.ConfigureClassifyApi();

    app.Run();
}
catch (Exception ex)
{
    Log.Fatal(ex, "Application terminated unexpectedly");
}
finally
{
    Log.CloseAndFlush();
}

